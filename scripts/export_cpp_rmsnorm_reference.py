#!/usr/bin/env python
"""Generate cpp/tests/rmsnorm_reference.hpp: reference values for test_rmsnorm.cpp.

    python scripts/export_cpp_rmsnorm_reference.py

The oracle is ``qwen3_scratch.layers.rmsnorm.rms_norm`` (verified against Hugging
Face ``Qwen3RMSNorm`` in M1/M2), evaluated in float32 with a fixed seed.
"""

from pathlib import Path

import torch
from export_cpp_ops_reference import cpp_array  # same folder: scripts/

from qwen3_scratch.layers.rmsnorm import rms_norm

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "rmsnorm_reference.hpp"
EPS = 1e-6


def main() -> None:
    g = torch.Generator().manual_seed(0)
    rand = lambda *shape: torch.randn(*shape, generator=g)  # noqa: E731

    x = rand(2, 3, 8)  # hidden states [B, T, H], H = 8
    w = 1.0 + 0.1 * rand(8)  # trained-looking weight (not all ones)
    q = rand(1, 2, 3, 4)  # per-head QK-Norm: [B, heads, T, head_dim], head_dim = 4
    wq = 1.0 + 0.1 * rand(4)
    big = rand(2, 8) * 1e4  # large activations
    small = rand(2, 8) * 1e-4  # tiny activations: eps is no longer negligible

    parts = [
        cpp_array("X", x),
        cpp_array("W", w),
        cpp_array("X_OUT", rms_norm(x, w, EPS)),
        cpp_array("Q", q),
        cpp_array("WQ", wq),
        cpp_array("Q_OUT", rms_norm(q, wq, EPS)),
        cpp_array("BIG", big),
        cpp_array("BIG_OUT", rms_norm(big, w, EPS)),
        cpp_array("SMALL", small),
        cpp_array("SMALL_OUT", rms_norm(small, w, EPS)),
    ]
    header = (
        "// GENERATED by scripts/export_cpp_rmsnorm_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32, eps {EPS}.\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
        f"const float EPS = {EPS:.8e}f;\n\n"
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()