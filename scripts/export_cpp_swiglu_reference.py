#!/usr/bin/env python
"""Generate cpp/tests/swiglu_reference.hpp: reference values for test_swiglu.cpp.

    python scripts/export_cpp_swiglu_reference.py

The oracle is ``qwen3_scratch.layers.swiglu.SwiGLUFeedForward`` (verified against
Hugging Face ``Qwen3MLP`` in M1/M2). Intermediate tensors (gate, up, hidden) are
exported too, so a failing C++ test shows WHICH step went wrong.
"""

from pathlib import Path

import torch
import torch.nn.functional as F
from export_cpp_ops_reference import cpp_array  # same folder: scripts/

from qwen3_scratch.layers.swiglu import SwiGLUFeedForward

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "swiglu_reference.hpp"
H_SIZE, I_SIZE = 8, 12  # tiny hidden_size / intermediate_size (Qwen3-0.6B: 1024 / 3072)


def main() -> None:
    torch.manual_seed(0)
    mlp = SwiGLUFeedForward(H_SIZE, I_SIZE).eval()  # random nn.Linear init, no bias
    x = torch.randn(2, 3, H_SIZE)  # [B, T, H]

    with torch.no_grad():
        gate = mlp.gate_proj(x)
        up = mlp.up_proj(x)
        hidden = F.silu(gate) * up
        out = mlp(x)

    parts = [
        cpp_array("GATE_W", mlp.gate_proj.weight),  # [I, H]
        cpp_array("UP_W", mlp.up_proj.weight),  # [I, H]
        cpp_array("DOWN_W", mlp.down_proj.weight),  # [H, I]
        cpp_array("X", x),
        cpp_array("GATE", gate),
        cpp_array("UP", up),
        cpp_array("HIDDEN", hidden),
        cpp_array("OUT", out),
    ]
    header = (
        "// GENERATED by scripts/export_cpp_swiglu_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32, H={H_SIZE}, I={I_SIZE}.\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
