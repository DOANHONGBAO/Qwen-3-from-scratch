#!/usr/bin/env python
"""Generate cpp/tests/attention_reference.hpp: reference values for test_attention.cpp.

    python scripts/export_cpp_attention_reference.py

The oracle is ``qwen3_scratch.layers.attention.GroupedQueryAttention`` (verified
against Hugging Face ``Qwen3Attention`` in M1/M2): GQA with 4 query heads sharing
2 KV heads, head_dim (8) independent of hidden_size / heads (16 / 4), QK-Norm,
split-half RoPE and a causal mask. Intermediate tensors are exported so a failing
C++ test shows which step went wrong.
"""

from pathlib import Path

import torch
from export_cpp_ops_reference import cpp_array  # same folder: scripts/

from qwen3_scratch.kv_cache import KVCache
from qwen3_scratch.layers.attention import GroupedQueryAttention
from qwen3_scratch.layers.rope import RotaryEmbedding, make_position_ids

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "attention_reference.hpp"
HIDDEN, HEADS, KV_HEADS, HEAD_DIM = 16, 4, 2, 8
THETA, EPS = 1_000_000.0, 1e-6


def main() -> None:
    torch.manual_seed(0)
    attn = GroupedQueryAttention(HIDDEN, HEADS, KV_HEADS, HEAD_DIM, rms_norm_eps=EPS).eval()
    with torch.no_grad():  # trained-looking QK-Norm weights (not all ones)
        attn.q_norm.weight.add_(0.1 * torch.randn(HEAD_DIM))
        attn.k_norm.weight.add_(0.1 * torch.randn(HEAD_DIM))
    rope = RotaryEmbedding(HEAD_DIM, THETA)
    x = torch.randn(2, 5, HIDDEN)  # [B, T, H]

    with torch.no_grad():
        cos, sin = rope(make_position_ids(5))
        out, trace = attn(x, cos, sin, return_trace=True)

        # Same input with a KV cache: prefill 3 tokens, then 1, then 1.
        cache = KVCache(1)
        chunks = []
        for start, end in [(0, 3), (3, 4), (4, 5)]:
            c, s = rope(make_position_ids(end - start, offset=start))
            chunks.append(attn(x[:, start:end], c, s, kv_cache=cache, layer_idx=0))
            cache.commit(end - start)
        out_cached = torch.cat(chunks, dim=1)

    parts = [
        cpp_array("Q_PROJ", attn.q_proj.weight),
        cpp_array("K_PROJ", attn.k_proj.weight),
        cpp_array("V_PROJ", attn.v_proj.weight),
        cpp_array("O_PROJ", attn.o_proj.weight),
        cpp_array("Q_NORM", attn.q_norm.weight),
        cpp_array("K_NORM", attn.k_norm.weight),
        cpp_array("X", x),
        cpp_array("Q_ROPE", trace.q_rope),  # [B, Nq, T, D] after QK-Norm + RoPE
        cpp_array("K_ROPE", trace.k_rope),  # [B, Nkv, T, D]
        cpp_array("OUT", out),  # [B, T, H]
        cpp_array("OUT_CACHED", out_cached),
    ]
    header = (
        "// GENERATED by scripts/export_cpp_attention_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32, H={HIDDEN}, Nq={HEADS}, "
        f"Nkv={KV_HEADS}, D={HEAD_DIM}.\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
        f"const int HIDDEN = {HIDDEN}, HEADS = {HEADS}, KV_HEADS = {KV_HEADS}, "
        f"HEAD_DIM = {HEAD_DIM};\n"
        f"const float THETA = {THETA:.8e}f, EPS = {EPS:.8e}f;\n\n"
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
