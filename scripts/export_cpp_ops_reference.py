
#!/usr/bin/env python
"""Generate cpp/tests/ops_reference.hpp: PyTorch reference values for test_ops.cpp.

    python scripts/export_cpp_ops_reference.py

PyTorch is the numerical oracle: inputs come from a fixed seed, outputs are computed
by torch in float32, and both are written as C++ arrays. Floats are printed with 9
significant digits, which round-trips every float32 exactly, so the C++ test sees
the very same input numbers as torch did.
"""

from pathlib import Path

import torch
import torch.nn.functional as F

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "ops_reference.hpp"


def cpp_array(name: str, t: torch.Tensor) -> str:
    values = ", ".join(f"{v:.8e}f" for v in t.detach().float().flatten().tolist())
    shape = ", ".join(str(s) for s in t.shape)
    return (
        f"const vector<int> {name}_SHAPE = {{{shape}}};\n"
        f"const vector<float> {name} = {{{values}}};\n"
    )


def main() -> None:
    g = torch.Generator().manual_seed(0)
    rand = lambda *shape: torch.randn(*shape, generator=g)  # noqa: E731

    a, b = rand(3, 5), rand(5, 4)  # matmul [3,5] x [5,4]
    x, w = rand(2, 3, 7), rand(6, 7)  # linear [2,3,7] x [6,7]^T -> [2,3,6]
    s = rand(3, 6) * 4  # softmax rows
    s[1] += 1000.0  # huge values: needs the max trick
    s[2, 4:] = -1e9  # "masked" entries -> probability 0
    e1, e2 = rand(4, 5), rand(4, 5)  # add / mul / scale
    v = torch.linspace(-8, 8, 17)  # silu over a range

    parts = [
        cpp_array("MATMUL_A", a),
        cpp_array("MATMUL_B", b),
        cpp_array("MATMUL_OUT", a @ b),
        cpp_array("LINEAR_X", x),
        cpp_array("LINEAR_W", w),
        cpp_array("LINEAR_OUT", F.linear(x, w)),
        cpp_array("SOFTMAX_IN", s),
        cpp_array("SOFTMAX_OUT", torch.softmax(s, dim=-1)),
        cpp_array("EW_A", e1),
        cpp_array("EW_B", e2),
        cpp_array("ADD_OUT", e1 + e2),
        cpp_array("MUL_OUT", e1 * e2),
        cpp_array("SCALE_OUT", e1 * 0.125),
        cpp_array("SILU_IN", v),
        cpp_array("SILU_OUT", F.silu(v)),
    ]
    header = (
        "// GENERATED by scripts/export_cpp_ops_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32.\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()