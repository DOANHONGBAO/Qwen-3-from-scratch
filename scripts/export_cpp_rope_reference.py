#!/usr/bin/env python
"""Generate cpp/tests/rope_reference.hpp: reference values for test_rope.cpp.

    python scripts/export_cpp_rope_reference.py

The oracle is ``qwen3_scratch.layers.rope`` (split-half RoPE, verified against
Hugging Face ``Qwen3RotaryEmbedding`` / ``apply_rotary_pos_emb`` in M1/M2).
"""

from pathlib import Path

import torch
from export_cpp_ops_reference import cpp_array  # same folder: scripts/

from qwen3_scratch.layers.rope import (
    apply_rope,
    compute_inv_freq,
    make_position_ids,
    rope_cos_sin,
)

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "rope_reference.hpp"
THETA = 1_000_000.0  # Qwen3-0.6B rope_theta
HEAD_DIM = 8  # tiny head_dim for the rotation tests (Qwen3-0.6B: 128)


def rope(x: torch.Tensor, start_pos: int) -> torch.Tensor:
    """RoPE for x [B, N, T, D] at positions start_pos .. start_pos + T - 1."""
    inv_freq = compute_inv_freq(x.shape[-1], THETA)
    cos, sin = rope_cos_sin(make_position_ids(x.shape[2], offset=start_pos), inv_freq)
    return apply_rope(x, cos, sin)


def main() -> None:
    g = torch.Generator().manual_seed(0)
    rand = lambda *shape: torch.randn(*shape, generator=g)  # noqa: E731

    q = rand(1, 2, 5, HEAD_DIM)  # prefill: positions 0..4
    k = rand(2, 1, 3, HEAD_DIM)  # continues after 7 cached tokens: positions 7..9
    far = rand(1, 1, 2, HEAD_DIM)  # long context: positions 30000..30001

    parts = [
        cpp_array("INV_FREQ_128", compute_inv_freq(128, THETA)),  # real Qwen3 table
        cpp_array("Q", q),
        cpp_array("Q_OUT", rope(q, 0)),
        cpp_array("K", k),
        cpp_array("K_OUT", rope(k, 7)),
        cpp_array("FAR", far),
        cpp_array("FAR_OUT", rope(far, 30000)),
    ]
    header = (
        "// GENERATED by scripts/export_cpp_rope_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32, rope_theta {THETA:g}.\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
        f"const float THETA = {THETA:.8e}f;\n\n"
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()