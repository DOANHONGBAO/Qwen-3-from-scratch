#!/usr/bin/env python
"""Generate cpp/tests/model_reference.hpp: a tiny random Qwen3 model for test_model.cpp.

    python scripts/export_cpp_model_reference.py

The oracle is ``qwen3_scratch.model.Qwen3ForCausalLM`` (bit-identical to Hugging
Face ``Qwen3ForCausalLM`` in M1/M2). The model is tiny and random (NOT a
checkpoint): every weight is exported by its Hugging Face checkpoint name, together
with the hidden state after each layer, the logits and greedy token ids, so the C++
test checks the name map, every layer, the KV cache and generation.
"""

from pathlib import Path

import torch
from export_cpp_ops_reference import cpp_array  # same folder: scripts/

from qwen3_scratch.config import Qwen3Config
from qwen3_scratch.generation import generate
from qwen3_scratch.model import Qwen3ForCausalLM

OUT = Path(__file__).resolve().parents[1] / "cpp" / "tests" / "model_reference.hpp"
CONFIG = Qwen3Config(
    vocab_size=48,
    hidden_size=16,
    intermediate_size=32,
    num_hidden_layers=2,
    num_attention_heads=4,
    num_key_value_heads=2,
    head_dim=8,  # Nq * D = 32 != hidden_size = 16, as in Qwen3-0.6B (2048 vs 1024)
    max_position_embeddings=64,
    rope_theta=1_000_000.0,
    rms_norm_eps=1e-6,
    tie_word_embeddings=True,
    dtype="float32",
)
NEW_TOKENS = 10
SCALE = 1.0  # weight std: gives varied greedy tokens (smaller stds repeat one token)


def cpp_string_list(name: str, values: list[str]) -> str:
    quoted = ", ".join('"' + v + '"' for v in values)
    return f"const vector<string> {name} = {{{quoted}}};\n"


def main() -> None:
    torch.manual_seed(0)
    model = Qwen3ForCausalLM(CONFIG).eval()
    with torch.no_grad():  # random weights with a fixed std, non-trivial norm weights
        for name, p in model.named_parameters():
            if "norm" in name:
                p.add_(0.1 * torch.randn(p.shape))
            else:
                p.copy_(SCALE * torch.randn(p.shape))

    ids = torch.randint(0, CONFIG.vocab_size, (2, 7), generator=torch.Generator().manual_seed(1))
    with torch.no_grad():
        out = model(ids, output_hidden_states=True)
        greedy = generate(model, ids[:1], max_new_tokens=NEW_TOKENS, use_cache=True)

    # Tied LM head: lm_head.weight IS model.embed_tokens.weight, not a separate tensor.
    weights = [(n, p) for n, p in model.state_dict().items() if n != "lm_head.weight"]
    parts = [
        cpp_string_list("WEIGHT_NAMES", [n for n, _ in weights]),
        *[cpp_array(f"W{i}", p) for i, (_, p) in enumerate(weights)],
        f"const vector<const vector<float>*> WEIGHT_VALUES = "
        f"{{{', '.join(f'&W{i}' for i in range(len(weights)))}}};\n",
        f"const vector<const vector<int>*> WEIGHT_SHAPES = "
        f"{{{', '.join(f'&W{i}_SHAPE' for i in range(len(weights)))}}};\n",
        cpp_array("IDS", ids.float()),
        *[cpp_array(f"HIDDEN_{i}", h) for i, h in enumerate(out.hidden_states)],
        cpp_array("LOGITS", out.logits),
        cpp_array("GREEDY", greedy.new_tokens[0].float()),
    ]
    c = CONFIG
    header = (
        "// GENERATED by scripts/export_cpp_model_reference.py - do not edit by hand.\n"
        f"// torch {torch.__version__}, seed 0, float32, tiny random Qwen3 (not a checkpoint).\n"
        "#pragma once\n#include <bits/stdc++.h>\nusing namespace std;\n\n"
        "// config.json of the tiny model\n"
        f'const string CONFIG_JSON = R"({{"vocab_size": {c.vocab_size}, '
        f'"hidden_size": {c.hidden_size}, "intermediate_size": {c.intermediate_size}, '
        f'"num_hidden_layers": {c.num_hidden_layers}, '
        f'"num_attention_heads": {c.num_attention_heads}, '
        f'"num_key_value_heads": {c.num_key_value_heads}, "head_dim": {c.head_dim}, '
        f'"max_position_embeddings": {c.max_position_embeddings}, '
        f'"rope_theta": {c.rope_theta:g}, "rms_norm_eps": {c.rms_norm_eps:g}, '
        f'"tie_word_embeddings": true, "attention_bias": false, "rope_scaling": null}})";\n\n'
    )
    OUT.write_text(header + "\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
